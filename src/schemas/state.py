"""Procurement Multi-Agent System State Definition."""

import operator
from typing import Annotated, Optional
from typing_extensions import TypedDict


class ProcurementState(TypedDict, total=False):
    """
    Shared state across the procurement multi-agent graph.

    Attributes:
        sku: Stock Keeping Unit identifier.
        current_stock: Current recorded stock level.
        reorder_threshold: Minimum stock safety limit before reordering.
        daily_burn_rate: Units consumed/sold per day on average.
        target_reorder_qty: Calculated order quantity.
        vendor_id: Target vendor/supplier identifier.
        unit_cost: Cost per unit from vendor.
        total_estimated_cost: Total calculated purchase order cost.
        po_number: Purchase order number generated by ERP (PO-XXXX).
        status: Current state status (PENDING_ANALYSIS, ANALYSIS_COMPLETE, DRAFT_NEEDED, DRAFT_CREATED, AWAITING_APPROVAL, APPROVED, REJECTED).
        approval_user: Slack user who approved or rejected the order.
        audit_log: Appended log of decisions and transitions.
    """

    sku: str
    current_stock: int
    reorder_threshold: int
    daily_burn_rate: float
    target_reorder_qty: int
    vendor_id: str
    unit_cost: float
    total_estimated_cost: float
    po_number: Optional[str]
    status: str
    approval_user: Optional[str]
    audit_log: Annotated[list[str], operator.add]
